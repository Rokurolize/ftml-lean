#!/usr/bin/env python3
"""REFCORR6 pooled CAPSTONE recheck on the retained 4,205-case list.

Uses pooled-cases.jsonl verbatim (no reassembly), the PHP artifact already
regenerated by regen_gates.py, and a freshly built capstone driver invoked
through the serial queue wrapper. The comparison logic is the canonical
conformance-capstone/compare.py canon_state unchanged, as in REPORT-REFCORR4.
"""
import json
import os
import shutil
import subprocess
import sys

ROOT = "/home/roku/.local/state/wikijump/muse-bhl/lean-ftml-refcorr6"
CAP = os.path.join(ROOT, "conformance-capstone")
sys.path.insert(0, CAP)
import compare
import pooled_run

WRAPPER = os.path.expanduser("~/.local/state/wikijump/muse-bhl/tools/lean-build.sh")
LEAN_WD = os.path.join(ROOT, "lean-ftml")
EXE = os.path.join(LEAN_WD, ".lake", "build", "bin",
                   "lean-ftml-conformance-capstone")


def main():
    cases_path = os.path.join(CAP, "pooled-cases.jsonl")
    php_path = os.path.join(CAP, "pooled-php-full.jsonl")
    lean_path = os.path.join(CAP, "pooled-lean.jsonl")
    comp_path = os.path.join(CAP, "pooled-comparison.txt")
    mism_path = os.path.join(CAP, "pooled-mismatches.json")
    for path in (lean_path, comp_path, mism_path):
        bak = path + ".before-refcorr6"
        if not os.path.exists(bak):
            shutil.copy2(path, bak)
    with open(cases_path, "rb") as fh:
        proc = subprocess.run([WRAPPER, LEAN_WD, EXE], input=fh.read(),
                              capture_output=True)
    with open(lean_path, "wb") as fh:
        fh.write(proc.stdout)
    with open(lean_path[:-6] + ".err", "wb") as fh:
        fh.write(proc.stderr)
    print("lean driver rc", proc.returncode, "bytes", len(proc.stdout),
          "stderr", len(proc.stderr))
    php = compare.load_jsonl(php_path)
    lean = compare.load_jsonl(lean_path)
    cases = pooled_run.read_jsonl(cases_path)
    mismatches = {}
    fatal_agree = 0
    npass = 0
    for rec in cases:
        cid = rec["id"]
        a, b = php.get(cid), lean.get(cid)
        if a is None or b is None:
            mismatches[cid] = {"components": ["missing-record"],
                               "source": rec.get("source", "")}
            continue
        af, bf = a.get("fatal"), b.get("fatal")
        if af is not None or bf is not None:
            if af is not None and af == bf:
                npass += 1
                fatal_agree += 1
            else:
                mismatches[cid] = {"components": ["fatal"],
                                   "detail": "php fatal=%r lean fatal=%r" % (af, bf),
                                   "source": rec.get("source", "")}
            continue
        if "error" in a or "error" in b:
            mismatches[cid] = {"components": ["error-record"],
                               "detail": "php error=%r lean error=%r" % (a.get("error"), b.get("error")),
                               "source": rec.get("source", "")}
            continue
        has_inc = ("inclusions" in a and "inclusions" in b)
        ca = compare.canon_state(a, include_doc_inc=has_inc)
        cb = compare.canon_state(b, include_doc_inc=has_inc)
        if ca == cb:
            npass += 1
        else:
            diff = [pooled_run.COMPONENTS[i]
                    for i in range(len(pooled_run.COMPONENTS)) if ca[i] != cb[i]]
            mismatches[cid] = {"components": diff,
                               "source": rec.get("source", "")}
    lines = ["pooled cases: %d (retained case list, no reassembly)" % len(cases),
             "PASS: %d/%d (including %d parse-fatal agreements)" % (npass, len(cases), fatal_agree),
             "MISMATCH: %d" % len(mismatches)]
    for cid in sorted(mismatches):
        lines.append("  %s: %s" % (cid, ",".join(mismatches[cid]["components"])))
    with open(comp_path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    with open(mism_path, "w") as fh:
        json.dump(mismatches, fh, indent=1, ensure_ascii=False)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
